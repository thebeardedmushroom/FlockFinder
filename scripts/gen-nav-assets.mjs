// Generate the Android assets for turn-by-turn navigation:
//
//   node scripts/gen-nav-assets.mjs
//
// - res/drawable/ic_nav_<name>.xml: the maneuver icons (src/lib/maneuverIcons.json) as vector
//   drawables, white on transparent as notification icons must be.
// - res/raw/camera_chime.wav: the camera alert sound (two short rising tones), played before
//   a camera announcement so it can't be mistaken for a turn prompt.
import { readFile, writeFile, mkdir } from "node:fs/promises";

const res = new URL("../src-tauri/gen/android/app/src/main/res/", import.meta.url);
const icons = JSON.parse(await readFile(new URL("../src/lib/maneuverIcons.json", import.meta.url), "utf8"));

const circle = ([cx, cy, r]) => `M${cx - r},${cy}a${r},${r} 0 1,0 ${2 * r},0a${r},${r} 0 1,0 ${-2 * r},0`;
const stroke = (d, alpha) =>
  `  <path android:pathData="${d}" android:strokeColor="#FFFFFFFF" android:strokeWidth="2.2"` +
  ` android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000"` +
  (alpha < 1 ? ` android:strokeAlpha="${alpha}"` : "") +
  ` />`;

await mkdir(new URL("drawable/", res), { recursive: true });
let count = 0;
for (const [name, icon] of Object.entries(icons)) {
  if (name.startsWith("_")) continue;
  const paths = [
    ...(icon.strokes ?? []).map((d) => stroke(d, 1)),
    ...(icon.faint ?? []).map((d) => stroke(d, 0.45)),
    ...(icon.dots ?? []).map((c) => `  <path android:pathData="${circle(c)}" android:fillColor="#FFFFFFFF" />`),
  ];
  const xml =
    `<?xml version="1.0" encoding="utf-8"?>\n` +
    `<!-- Generated by scripts/gen-nav-assets.mjs from src/lib/maneuverIcons.json. -->\n` +
    `<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp"` +
    ` android:viewportWidth="24" android:viewportHeight="24">\n${paths.join("\n")}\n</vector>\n`;
  await writeFile(new URL(`drawable/ic_nav_${name}.xml`, res), xml);
  count++;
}

// 16-bit mono PCM WAV.
const rate = 22050;
const tones = [
  [1047, 0.11],
  [1397, 0.17],
];
const gap = 0.03;
const samples = [];
for (const [freq, dur] of tones) {
  const n = Math.round(dur * rate);
  for (let i = 0; i < n; i++) {
    const t = i / rate;
    const attack = Math.min(1, t / 0.008);
    const decay = Math.exp(-t * 14);
    samples.push(Math.sin(2 * Math.PI * freq * t) * attack * decay * 0.6);
  }
  for (let i = 0; i < Math.round(gap * rate); i++) samples.push(0);
}
const data = Buffer.alloc(samples.length * 2);
samples.forEach((s, i) => data.writeInt16LE(Math.round(Math.max(-1, Math.min(1, s)) * 32767), i * 2));
const header = Buffer.alloc(44);
header.write("RIFF", 0);
header.writeUInt32LE(36 + data.length, 4);
header.write("WAVE", 8);
header.write("fmt ", 12);
header.writeUInt32LE(16, 16);
header.writeUInt16LE(1, 20); // PCM
header.writeUInt16LE(1, 22); // mono
header.writeUInt32LE(rate, 24);
header.writeUInt32LE(rate * 2, 28);
header.writeUInt16LE(2, 32);
header.writeUInt16LE(16, 34);
header.write("data", 36);
header.writeUInt32LE(data.length, 40);
await mkdir(new URL("raw/", res), { recursive: true });
await writeFile(new URL("raw/camera_chime.wav", res), Buffer.concat([header, data]));
console.log(`${count} icons, camera_chime.wav (${((samples.length / rate) * 1000).toFixed(0)} ms)`);
